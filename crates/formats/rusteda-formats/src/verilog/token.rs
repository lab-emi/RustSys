//! Tokens (VERILOG-REQ-0001).

use crate::verilog::span::Span;

/// Token kinds.
#[derive(Debug, Clone, PartialEq)]
pub enum Tok {
    /// Simple identifier.
    Ident(String),
    /// Escaped identifier, stored without the leading backslash.
    EscIdent(String),
    /// System identifier including the `$`.
    SysIdent(String),
    /// Reserved keyword.
    Kw(&'static str),
    /// Unsigned decimal digits (underscores removed).
    Dec(String),
    /// Based literal without size: `'[s]<base><digits>`; digits lower-case, underscores removed.
    Based {
        signed: bool,
        base: char,
        digits: String,
    },
    /// `'0`, `'1`, `'x`, `'z` (lower-case).
    UnbasedUnsized(char),
    /// Real literal text.
    Real(String),
    /// Time literal text (`10ns`).
    Time(String),
    /// String literal bytes after escape processing.
    Str(Vec<u8>),
    /// Operator or punctuator.
    Op(&'static str),
    /// `'{`
    TickBrace,
    /// `` `default_nettype `` directive value, passed to the parser.
    DefaultNettype(String),
    /// Case attributes (`full_case`, `parallel_case`) of the attribute instances directly
    /// before a `case`, `casez` or `casex` statement or its qualifier (VERILOG-REQ-0102).
    CaseAttrs(crate::verilog::ast::CaseAttrs),
    /// End of input.
    Eof,
}

/// A token with its location.
#[derive(Debug, Clone, PartialEq)]
pub struct Token {
    pub tok: Tok,
    pub span: Span,
}

