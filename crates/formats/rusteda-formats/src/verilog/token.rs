#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keyword_table_is_sorted() {
        for w in KEYWORDS.windows(2) {
            assert!(w[0] < w[1], "{} >= {}", w[0], w[1]);
        }
        assert_eq!(keyword("always_ff"), Some("always_ff"));
        assert_eq!(keyword("clk"), None);
    }
}
