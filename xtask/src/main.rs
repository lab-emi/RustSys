//! Repository automation. Run with `cargo xtask <command>`.
//!
//! - `fixtures`: regenerates `verification/fixtures/synthetic/` from `rustsys-fixtures`.
//! - `layout`: checks the repository layout rules on tracked (and untracked, not ignored) files:
//!   locations, sizes and dependency edges ([`layout`]).
//! - `coverage`: writes the requirement-to-test matrix to `docs/verification/requirements.md`.
//! - `verify [synth] [--gpu]`: runs the verification suites ([`verify`]).
//! - `pdk fetch [--dir DIR]`: downloads the pinned standard-cell libraries of
//!   `verification/pdks.toml` and verifies their hashes ([`pdk`]).
//! - `verify pdk [--dir DIR] [--require] [--timeout SECS]`: synthesizes and checks the fixture
//!   designs with those libraries ([`pdk`]).
//! - `shared <check|update|diff OTHER>`: checks or rewrites the manifest of the files shared with
//!   the other RustEDA tool repositories, or compares them with another repository ([`shared`]).

#![allow(clippy::print_stdout)]

mod coverage;
