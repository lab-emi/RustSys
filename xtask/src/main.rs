mod layout;
mod pdk;
mod shared;
#[cfg(test)]
mod testutil;
mod verify;

use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

/// First line every Rust source must have (assembled so that license scanners do not read it as
/// a tag of this file).
pub(crate) const SPDX_HEADER: &str = concat!("// SPDX-", "License-Identifier: Apache-2.0");

/// The workspace root (the parent of this crate's directory).
pub(crate) fn root() -> PathBuf {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    manifest
        .parent()
        .map_or(manifest.clone(), Path::to_path_buf)
}

pub(crate) fn write(path: &Path, text: &str) -> Result<(), String> {
    if let Some(d) = path.parent() {
        std::fs::create_dir_all(d).map_err(|e| format!("{}: {e}", d.display()))?;
    }
    std::fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))
}

fn fixtures() -> Result<(), String> {
    let base = root().join("verification/fixtures/synthetic/synth");
    if base.exists() {
        std::fs::remove_dir_all(&base).map_err(|e| e.to_string())?;
    }
    for v in rustsys_fixtures::liberty::Variant::ALL {
        write(
            &base.join("lib").join(format!("{}.lib", v.name())),
            &rustsys_fixtures::liberty::library(v),
        )?;
    }
    let mut index = String::from("# Generated by `cargo xtask fixtures`; do not edit.\n");
    for d in rustsys_fixtures::rtl::CORPUS {
        let dir = base.join("rtl").join(d.name);
        let mut files = Vec::new();
        for (n, t) in d.files {
            write(
                &dir.join(n),
                &format!("// Generated by `cargo xtask fixtures`; do not edit.\n{t}"),
            )?;
            files.push(format!("\"{n}\""));
        }
        index.push_str(&format!(
            "\n[[design]]\nname = \"{}\"\ntop = \"{}\"\nfiles = [{}]\n",
            d.name,
            d.top,
            files.join(", ")
        ));
    }
    write(&base.join("rtl/index.toml"), &index)?;
    println!("wrote {}", base.display());
    Ok(())
}

/// Files to check: tracked files and untracked files that git does not ignore, without the
/// local-only files that are never part of the product tree.
fn files() -> Vec<String> {
    let out = Command::new("git")
        .args(["ls-files", "--cached", "--others", "--exclude-standard"])
        .current_dir(root())
        .output();
    let mut v: Vec<String> = match out {
        Ok(o) if o.status.success() => String::from_utf8_lossy(&o.stdout)
            .lines()
            .map(str::to_string)
            .collect(),
        _ => Vec::new(),
    };
    let local = |p: &str| {
        let lower = p.to_ascii_lowercase();
        lower == "agents.md"
            || lower == "claude.md"
            || lower.starts_with(".work/")
            || lower.starts_with("target/")
            || lower.starts_with(".claude/")
            || p == "setup-local-guardrails.sh"
    };
    v.retain(|p| !local(p));
    // Files deleted from the working tree but still in the index are not checked.
    let r = root();
    v.retain(|p| r.join(p).exists());
    v.sort();
    v.dedup();
    v
}

/// The commands, printed for a missing or unknown command.
const USAGE: &str = "usage: cargo xtask <command>
  fixtures
  layout
  coverage
  verify [synth] [--gpu]
  verify pdk [--dir DIR] [--require] [--timeout SECS]
  pdk fetch [--dir DIR]
  shared <check|update|diff OTHER>";

/// `verify [product] [--gpu]`; the product defaults to `synth`.
fn verify_args(args: &[String]) -> Result<(String, verify::Options), String> {
    let mut product = None;
    let mut o = verify::Options::default();
    for a in args {
        match a.as_str() {
            "--gpu" => o.gpu = true,
            s if s.starts_with('-') => return Err(format!("unknown option '{s}'")),
            s if product.is_none() => product = Some(s.to_string()),
            s => return Err(format!("unexpected argument '{s}'")),
        }
    }
    Ok((product.unwrap_or_else(|| "synth".into()), o))
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let r = match args.first().map(String::as_str) {
        Some("fixtures") => fixtures(),
        Some("layout") => layout::run(&root(), &files()),
        Some("coverage") => coverage::run(&root()),
        Some("pdk") => {
            pdk::fetch_args(args.get(1..).unwrap_or_default()).and_then(|o| pdk::fetch(&root(), &o))
        }
        Some("verify") if args.get(1).is_some_and(|a| a == "pdk") => {
            pdk::verify_args(args.get(2..).unwrap_or_default())
                .and_then(|o| pdk::verify(&root(), &o))
        }
        Some("verify") => verify_args(args.get(1..).unwrap_or_default())
            .and_then(|(p, o)| verify::run(&root(), &p, o)),
        Some("shared") => shared::run(&root(), args.get(1..).unwrap_or_default()),
        _ => Err(USAGE.into()),
    };
    match r {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("{e}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    // `verify synth --gpu` parses and the product defaults to `synth`; unknown options and a
    // second product fail.
    #[test]
    fn verify_arguments() {
        let a = |s: &[&str]| verify_args(&s.iter().map(|x| x.to_string()).collect::<Vec<_>>());
        assert_eq!(
            a(&["synth", "--gpu"]),
            Ok(("synth".to_string(), verify::Options { gpu: true }))
        );
        assert_eq!(
            a(&["--gpu"]),
            Ok(("synth".to_string(), verify::Options { gpu: true }))
        );
        assert_eq!(
            a(&[]),
            Ok(("synth".to_string(), verify::Options::default()))
        );
        assert!(a(&["synth", "--fast"]).is_err());
        assert!(a(&["synth", "check"]).is_err());
    }
}
